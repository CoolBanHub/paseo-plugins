import { chmodSync, mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";

/**
 * Outbound attachments. The agent cannot call back into the plugin process, so
 * the plugin installs a tiny CLI in plugin-data that drops a JSON request into
 * an outbox directory. The dispatcher polls that directory, uploads the files
 * with lark-cli and replies inside the topic.
 *
 * This is a deliberate side channel: it must validate paths and sizes because
 * a prompt-injected agent could otherwise exfiltrate arbitrary local files.
 */

export const outboxRequestSchema = z.object({
  version: z.number().default(1),
  chatId: z.string().min(1),
  topicKey: z.string().nullable().default(null),
  message: z.string().nullable().default(null),
  images: z.array(z.string()).default([]),
  files: z.array(z.string()).default([]),
});

export type OutboxRequest = z.output<typeof outboxRequestSchema>;

const MAX_FILES_PER_REQUEST = 6;
const HELPER_SCRIPT = "lark-bot-send.mjs";
const HELPER_WRAPPER = "lark-bot-send";
const MEMBERS_HELPER_SCRIPT = "lark-bot-members.mjs";
const MEMBERS_HELPER_WRAPPER = "lark-bot-members";

function helperSource(): string {
  // The shebang uses the daemon's own Node binary: the agent's shell PATH may
  // not contain nvm's bin directory.
  return [
    "// Generated by paseo-lark-bot. Writes one JSON request into the plugin outbox.",
    "import { mkdirSync, renameSync, writeFileSync } from 'node:fs';",
    "import { randomUUID } from 'node:crypto';",
    "import { dirname, join, resolve } from 'node:path';",
    "import { fileURLToPath } from 'node:url';",
    "const args = process.argv.slice(2);",
    "const images = [];",
    "const files = [];",
    "let message = null;",
    "let chatId = process.env.LARK_BOT_CHAT_ID || '';",
    "let topicKey = process.env.LARK_BOT_TOPIC || null;",
    "let outbox = process.env.LARK_BOT_OUTBOX || '';",
    "for (let i = 0; i < args.length; i += 1) {",
    "  const arg = args[i];",
    "  const value = args[i + 1];",
    "  if (arg === '--help' || arg === '-h') {",
    "    console.log('usage: lark-bot-send [--image PATH]... [--file PATH]... [--message TEXT] [--chat CHAT_ID] [--topic TOPIC_KEY]');",
    "    process.exit(0);",
    "  }",
    "  if (value === undefined) { console.error('missing value for ' + arg); process.exit(2); }",
    "  if (arg === '--image') { images.push(resolve(value)); i += 1; continue; }",
    "  if (arg === '--file') { files.push(resolve(value)); i += 1; continue; }",
    "  if (arg === '--message') { message = value; i += 1; continue; }",
    "  if (arg === '--chat') { chatId = value; i += 1; continue; }",
    "  if (arg === '--topic') { topicKey = value; i += 1; continue; }",
    "  if (arg === '--outbox') { outbox = value; i += 1; continue; }",
    "  console.error('unknown option: ' + arg); process.exit(2);",
    "}",
    "if (!outbox) outbox = join(dirname(dirname(fileURLToPath(import.meta.url))), 'outbox');",
    "if (!chatId) { console.error('missing chat id (--chat or LARK_BOT_CHAT_ID)'); process.exit(2); }",
    "if (images.length === 0 && files.length === 0 && !message) {",
    "  console.error('nothing to send: pass --image, --file or --message');",
    "  process.exit(2);",
    "}",
    "mkdirSync(outbox, { recursive: true });",
    "const target = join(outbox, randomUUID() + '.json');",
    "const temporary = target + '.tmp';",
    "writeFileSync(temporary, JSON.stringify({ version: 1, chatId, topicKey, message, images, files }), { mode: 0o600 });",
    "renameSync(temporary, target);",
    "console.log('queued: ' + target);",
  ].join("\n") + "\n";
}

/**
 * Write (or refresh) the helper script under `<root>/bin`. Returns its
 * absolute path, which is quoted in the agent's system prompt. Failures are
 * reported to the caller so it can log them instead of failing startup.
 */
export function installOutboxHelper(root: string, execPath: string): string {
  const binDir = join(root, "bin");
  mkdirSync(binDir, { recursive: true });
  const script = join(binDir, HELPER_SCRIPT);
  writeFileSync(script, helperSource(), { mode: 0o644 });
  // A shell wrapper keeps working when the daemon's Node path (or the plugin
  // data path) contains spaces; a shebang cannot quote its interpreter.
  const quote = (value: string) => "'" + value.replace(/'/g, "'\\''") + "'";
  const wrapper = join(binDir, HELPER_WRAPPER);
  writeFileSync(wrapper, `#!/bin/sh\nexec ${quote(execPath)} ${quote(script)} "$@"\n`, { mode: 0o755 });
  chmodSync(wrapper, 0o755);
  return wrapper;
}

function membersHelperSource(): string {
  return [
    "// Generated by paseo-lark-bot. Lists/searches chat members via lark-cli.",
    "import { execFileSync } from 'node:child_process';",
    "const args = process.argv.slice(2);",
    "let query = '';",
    "let chatId = process.env.LARK_BOT_CHAT_ID || '';",
    "let cli = process.env.LARK_BOT_CLI || 'lark-cli';",
    "let asJson = false;",
    "for (let i = 0; i < args.length; i += 1) {",
    "  const arg = args[i];",
    "  const value = args[i + 1];",
    "  if (arg === '--help' || arg === '-h') { console.log('usage: lark-bot-members [--query NAME] [--chat CHAT_ID] [--json]'); process.exit(0); }",
    "  if (arg === '--query' || arg === '-q') { if (value === undefined) { console.error('missing value for ' + arg); process.exit(2); } query = value; i += 1; continue; }",
    "  if (arg === '--chat') { if (value === undefined) { console.error('missing value for ' + arg); process.exit(2); } chatId = value; i += 1; continue; }",
    "  if (arg === '--cli') { if (value === undefined) { console.error('missing value for ' + arg); process.exit(2); } cli = value; i += 1; continue; }",
    "  if (arg === '--json') { asJson = true; continue; }",
    "  console.error('unknown option: ' + arg); process.exit(2);",
    "}",
    "if (!chatId) { console.error('missing chat id (--chat or LARK_BOT_CHAT_ID)'); process.exit(2); }",
    "let stdout = '';",
    "try {",
    "  stdout = execFileSync(cli, ['im', '+chat-members-list', '--chat-id', chatId, '--page-all', '--format', 'json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });",
    "} catch (error) {",
    "  const detail = error && error.stderr ? String(error.stderr) : error && error.message ? error.message : String(error);",
    "  console.error('failed to list members: ' + detail.trim());",
    "  process.exit(1);",
    "}",
    "const start = stdout.indexOf('{');",
    "let payload = null;",
    "try { payload = start >= 0 ? JSON.parse(stdout.slice(start)) : null; } catch {}",
    "if (!payload || payload.ok !== true) { console.error('lark-cli did not return ok=true'); process.exit(1); }",
    "const data = payload.data || {};",
    "const needle = query.trim().toLowerCase();",
    "const results = [];",
    "const push = (items, kind) => {",
    "  if (!Array.isArray(items)) return;",
    "  for (const item of items) {",
    "    if (!item || typeof item !== 'object') continue;",
    "    const openId = item.member_id;",
    "    if (typeof openId !== 'string' || !openId.startsWith('ou_')) continue;",
    "    const name = typeof item.name === 'string' ? item.name : '';",
    "    if (needle && !name.toLowerCase().includes(needle) && !openId.toLowerCase().includes(needle)) continue;",
    "    results.push({ kind, name, openId, appId: item.app_id || item.bot_id || null });",
    "  }",
    "};",
    "push(data.bots, 'bot');",
    "push(data.users, 'user');",
    "const limited = results.slice(0, 50);",
    "if (asJson) { console.log(JSON.stringify(limited, null, 2)); process.exit(0); }",
    "if (limited.length === 0) { console.log('没有找到匹配的群成员。'); process.exit(0); }",
    "for (const entry of limited) console.log('[' + (entry.kind === 'bot' ? '机器人' : '成员') + '] ' + (entry.name || '(未命名)') + ' · ' + entry.openId + (entry.appId ? ' · app ' + entry.appId : ''));",
  ].join("\n") + "\n";
}

/** Install the member-search helper used by the agent's @ workflow. */
export function installMembersHelper(root: string, execPath: string): string {
  const binDir = join(root, "bin");
  mkdirSync(binDir, { recursive: true });
  const script = join(binDir, MEMBERS_HELPER_SCRIPT);
  writeFileSync(script, membersHelperSource(), { mode: 0o644 });
  const quote = (value: string) => "'" + value.replace(/'/g, "'\\''") + "'";
  const wrapper = join(binDir, MEMBERS_HELPER_WRAPPER);
  writeFileSync(wrapper, `#!/bin/sh\nexec ${quote(execPath)} ${quote(script)} "$@"\n`, { mode: 0o755 });
  chmodSync(wrapper, 0o755);
  return wrapper;
}

export interface OutboxWatcherOptions {
  dir: string;
  /** Handles one validated request; throwing marks the file as failed. */
  onRequest: (request: OutboxRequest) => Promise<void>;
  log?: (message: string, detail?: unknown) => void;
  intervalMs?: number;
  /** Max requests processed per tick (default 5). */
  batchSize?: number;
}

export function createOutboxWatcher(options: OutboxWatcherOptions) {
  const log = options.log ?? (() => undefined);
  let timer: ReturnType<typeof setInterval> | null = null;
  let stopped = false;
  let processing = false;

  function fail(file: string): void {
    try {
      renameSync(join(options.dir, file), join(options.dir, file.replace(/\.json$/, ".failed")));
    } catch {
      // The file may already be gone; nothing else to do.
    }
  }

  async function processFile(file: string): Promise<void> {
    let request: OutboxRequest;
    try {
      const parsed = outboxRequestSchema.safeParse(JSON.parse(readFileSync(join(options.dir, file), "utf8")));
      if (!parsed.success) {
        log("忽略无效的附件请求", parsed.error.issues[0]?.message ?? file);
        fail(file);
        return;
      }
      request = parsed.data;
    } catch (error) {
      log("读取附件请求失败", error instanceof Error ? error.message : String(error));
      fail(file);
      return;
    }
    if (request.images.length + request.files.length > MAX_FILES_PER_REQUEST) {
      log("附件请求超过数量上限", file);
      fail(file);
      return;
    }
    try {
      await options.onRequest(request);
      // A successful request is consumed; losing it after the reply is fine.
      renameSync(join(options.dir, file), join(options.dir, file.replace(/\.json$/, ".done")));
    } catch (error) {
      log("处理附件请求失败", error instanceof Error ? error.message : String(error));
      fail(file);
    }
  }

  async function tick(): Promise<void> {
    if (stopped || processing) return;
    processing = true;
    try {
      let files: string[];
      try {
        files = readdirSync(options.dir)
          .filter((name) => name.endsWith(".json"))
          .sort()
          .slice(0, options.batchSize ?? 5);
      } catch {
        return;
      }
      for (const file of files) await processFile(file);
    } finally {
      processing = false;
    }
  }

  return {
    tick,
    start(): void {
      if (timer || stopped) return;
      void tick();
      timer = setInterval(() => {
        void tick();
      }, options.intervalMs ?? 2_000);
      timer.unref?.();
    },
    stop(): void {
      stopped = true;
      if (timer) clearInterval(timer);
      timer = null;
    },
  };
}

/** True when `candidate` resolves inside one of the allowed roots. */
export function isInsideRoots(candidate: string, roots: Iterable<string>): boolean {
  const normalized = candidate.endsWith("/") ? candidate.slice(0, -1) : candidate;
  for (const root of roots) {
    const base = root.endsWith("/") ? root.slice(0, -1) : root;
    if (normalized === base || normalized.startsWith(base + "/")) return true;
  }
  return false;
}
